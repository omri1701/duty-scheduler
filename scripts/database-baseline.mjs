// Deterministic packaging only. SQL in supabase/schemas and reference-data is authoritative.
import {readFile, writeFile, readdir} from 'node:fs/promises';
import {fileURLToPath} from 'node:url';
import path from 'node:path';
import assert from 'node:assert/strict';
import {createHash} from 'node:crypto';
import {spawnSync} from 'node:child_process';

const root = fileURLToPath(new URL('../supabase/', import.meta.url));
const manifest = JSON.parse(await readFile(path.join(root, 'baseline.json'), 'utf8'));
const args = process.argv.slice(2);
const container = args[0] === '--verify-local' ? args[1] : null;
const bundle = args[0] === '--bundle';
const check = args[0] === '--check' || Boolean(container) || bundle;
assert(args.length === 0 || (args.length === 1 && ['--check', '--bundle'].includes(args[0]))
  || (args.length === 2 && container), 'Use --check, --bundle, or --verify-local <local-container>');
const compiled = {};
async function sqlFiles(dir) {
  const entries = await readdir(path.join(root, dir), {withFileTypes: true});
  return (await Promise.all(entries.map(entry => entry.isDirectory()
    ? sqlFiles(`${dir}/${entry.name}`)
    : entry.name.endsWith('.sql') ? [`${dir}/${entry.name}`] : []))).flat();
}
const sources = [...manifest.schema, ...manifest.referenceData];
assert.equal(new Set(sources).size, sources.length, 'Duplicate source in baseline manifest');
assert.deepEqual([...sources].sort(), [...await sqlFiles('schemas'), ...await sqlFiles('reference-data')].sort(), 'Every SQL source must appear exactly once in the dependency manifest');
const configPath = path.join(root, 'config.toml');
const config = (await readFile(configPath, 'utf8')).replaceAll('\r\n', '\n');
const paths = `schema_paths = [\n${manifest.schema.map(source => `  "./${source}",`).join('\n')}\n]`;
const updatedConfig = config.replace(/schema_paths = \[[\s\S]*?\]/, paths);
assert.notEqual(updatedConfig.indexOf(paths), -1, 'Missing schema_paths in CLI config');
if (check) assert.equal(config, updatedConfig, 'CLI schema_paths must match the dependency manifest');
else await writeFile(configPath, updatedConfig, 'utf8');
for (const [group, suffix] of [['schema', 'clean_baseline'], ['referenceData', 'required_reference_data']]) {
  const matches = (await readdir(path.join(root, 'migrations'))).filter(name => name.endsWith(`_${suffix}.sql`));
  assert.equal(matches.length, 1, `Expected one CLI-created ${suffix} migration`);
  let content = '-- GENERATED by node scripts/database-baseline.mjs. Edit canonical sources, never this copy.\n';
  if (group === 'schema') content += "-- SQL-language function dependencies are resolved after all functions exist.\nSET check_function_bodies = false;\nSET search_path = '';\n\n";
  for (const source of manifest[group]) {
    assert.match(source, /^(schemas|reference-data)\/[\w/.-]+\.sql$/, 'Invalid source path');
    const sql = (await readFile(path.join(root, source), 'utf8')).replaceAll('\r\n', '\n').trim();
    assert(sql.length > 0, `Empty source: ${source}`);
    content += `-- Source: ${source}\n${sql}\n\n`;
  }
  if (group === 'schema') content += "RESET check_function_bodies;\nRESET search_path;\nNOTIFY pgrst, 'reload schema';\n";
  const target = path.join(root, 'migrations', matches[0]);
  const existing = (await readFile(target, 'utf8')).replaceAll('\r\n', '\n');
  const hash = value => createHash('sha256').update(value).digest('hex');
  assert.equal(hash(existing), manifest.frozenMigrations[matches[0]], 'Applied baseline changed: never rewrite migration history');
  if (!bundle && (await readdir(path.join(root, 'migrations'))).filter(name => name.endsWith('.sql')).length === 2) {
    assert.equal(content, existing, 'Canonical sources changed without an incremental migration');
  }
  if (!check) {
    assert.equal(hash(content), manifest.frozenMigrations[matches[0]], 'Use a new incremental migration for changed sources');
    await writeFile(target, content, 'utf8');
  }
  compiled[group] = content;
  if (!bundle) console.log(`Verified immutable ${matches[0]}`);
}
if (bundle) process.stdout.write(compiled.schema + compiled.referenceData);
if (container) {
  assert.match(container, /^supabase_db_[\w-]+$/, 'Only a disposable local Supabase container is accepted');
  function sql(query) {
    const result = spawnSync('docker', ['exec', '-i', container, 'psql', '-U', 'postgres', '-qAt', '-v', 'ON_ERROR_STOP=1'], {input: query, encoding: 'utf8'});
    assert.equal(result.status, 0, result.stderr);
    return result.stdout.trim();
  }
  sql(await readFile(path.join(root, 'tests/schema.sql'), 'utf8'));
  const fingerprint = await readFile(path.join(root, 'tests/fingerprint.sql'), 'utf8');
  const actual = sql(fingerprint);
  // Instantiate only application objects beside the empty local installation.
  // Supabase-managed Auth stays intact. No hosted connection or credentials accepted.
  assert.equal(sql("select count(*) from pg_namespace where nspname in ('duty_expected','duty_expected_private')"), '0');
  try {
    const source = (compiled.schema + compiled.referenceData).replaceAll('duty_private', 'duty_expected_private').replaceAll('public.', 'duty_expected.');
    sql(`BEGIN; CREATE SCHEMA duty_expected; ${source} COMMIT;`);
    const expectedQuery = fingerprint.replaceAll("'public'", "'duty_expected'").replaceAll("'duty_private'", "'duty_expected_private'")
      .replace("f.nspname||'.'", "replace(replace(f.nspname,'duty_expected_private','duty_private'),'duty_expected','public')||'.'")
      .replace('ORDER BY name)::text)', "ORDER BY name)::text,'duty_expected_private','duty_private'),'duty_expected','public'))")
      .replace('pg_catalog.md5(pg_catalog.jsonb_agg(', 'pg_catalog.md5(replace(replace(pg_catalog.jsonb_agg(');
    assert.equal(sql(expectedQuery), actual, 'Migration replay differs from canonical schema/permissions');
    for (const file of manifest.referenceData) {
      const table = path.basename(file, '.sql');
      assert.match(table, /^duty_\w+$/);
      assert.equal(sql(`select (select jsonb_agg(row order by row::text) from (select to_jsonb(t) row from public.${table} t) a)
        is not distinct from (select jsonb_agg(row order by row::text) from (select to_jsonb(t) row from duty_expected.${table} t) b)`), 't', `Reference data differs: ${table}`);
    }
    console.log('PASS: complete canonical schema, permissions and required rows match migration replay');
  } finally {
    sql('DROP SCHEMA IF EXISTS duty_expected CASCADE; DROP SCHEMA IF EXISTS duty_expected_private CASCADE;');
  }
}
